create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null unique
    check (username = btrim(username) and char_length(username) between 1 and 50),
  created_at timestamptz not null default now()
);

create unique index profiles_username_lower_key
  on public.profiles (lower(username));

create table public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  content text
    check (content is null or char_length(btrim(content)) between 1 and 10000),
  is_reshare boolean not null default false,
  original_post_id bigint references public.posts (id) on delete set null,
  created_at timestamptz not null default now()
);

create index posts_created_at_idx on public.posts (created_at desc);
create index posts_user_id_idx on public.posts (user_id);
create index posts_original_post_id_idx on public.posts (original_post_id);

create table public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  content text not null
    check (char_length(btrim(content)) between 1 and 5000),
  created_at timestamptz not null default now()
);

create index comments_post_id_created_at_idx
  on public.comments (post_id, created_at);

create table public.likes (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint likes_post_id_user_id_key unique (post_id, user_id)
);

create index likes_user_id_idx on public.likes (user_id);

create function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, new.raw_user_meta_data ->> 'username');
  return new;
end;
$$;

revoke all on function public.handle_new_user() from public;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.comments enable row level security;
alter table public.likes enable row level security;

grant usage on schema public to anon, authenticated;

revoke all on table public.profiles, public.posts, public.comments, public.likes
  from anon, authenticated;

grant select on table public.profiles, public.posts, public.comments, public.likes
  to anon, authenticated;
grant insert, update, delete on table public.posts to authenticated;
grant insert, delete on table public.comments to authenticated;
grant insert, delete on table public.likes to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "Profiles are publicly readable"
  on public.profiles for select
  to anon, authenticated
  using (true);

create policy "Posts are publicly readable"
  on public.posts for select
  to anon, authenticated
  using (true);

create policy "Users can create their own posts"
  on public.posts for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can update their own posts"
  on public.posts for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own posts"
  on public.posts for delete
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "Comments are publicly readable"
  on public.comments for select
  to anon, authenticated
  using (true);

create policy "Users can create their own comments"
